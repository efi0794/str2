SET DEFINE OFF

-- HoYoLABから自動取得した有効なリソース観測値を保存
CREATE TABLE hoyo_resource_snapshots (
  snapshot_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id NUMBER(10) NOT NULL REFERENCES users(user_id),
  game_id NUMBER(10) NOT NULL REFERENCES games(game_id),
  current_amount NUMBER(8) NOT NULL CHECK (current_amount >= 0),
  max_amount NUMBER(8) NOT NULL CHECK (max_amount > 0),
  observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
  -- OracleはTIMESTAMP WITH TIME ZONEをUNIQUEに使えないため、正規化したUTC文字列で重複を防止
  observed_at_key VARCHAR2(24 CHAR) NOT NULL,
  CONSTRAINT ck_snapshot_range CHECK (current_amount <= max_amount),
  CONSTRAINT uq_snapshot_observed UNIQUE (user_id, game_id, observed_at_key)
);

-- MANUAL=実際に使用した時刻と量を手入力
-- ESTIMATED=連続観測間の「見かけの減少」を検出した時刻。正確な使用時刻ではない。
CREATE TABLE stamina_use_logs (
  use_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id NUMBER(10) NOT NULL REFERENCES users(user_id),
  game_id NUMBER(10) NOT NULL REFERENCES games(game_id),
  amount NUMBER(8) NOT NULL CHECK (amount > 0),
  used_at TIMESTAMP WITH TIME ZONE NOT NULL,
  source VARCHAR2(12 CHAR) NOT NULL
    CONSTRAINT ck_stamina_source CHECK (source IN ('MANUAL','ESTIMATED')),
  note VARCHAR2(200 CHAR),
  snapshot_id NUMBER REFERENCES hoyo_resource_snapshots(snapshot_id),
  CONSTRAINT uq_stamina_snapshot UNIQUE (snapshot_id)
);

CREATE INDEX ix_stamina_history_user ON stamina_use_logs(user_id, used_at, game_id);
CREATE INDEX ix_snapshot_game_time ON hoyo_resource_snapshots(user_id, game_id, observed_at);

-- 7. 消費履歴VIEW（時刻は日本時間に変換）
CREATE OR REPLACE VIEW v_stamina_use_history AS
SELECT s.use_id, s.user_id, s.game_id, g.game_code, g.game_name,
       s.amount, s.source, s.note, s.used_at,
       TO_CHAR(s.used_at AT TIME ZONE '+09:00','YYYY-MM-DD HH24:MI') AS used_at_jst,
       TO_NUMBER(TO_CHAR(s.used_at AT TIME ZONE '+09:00','HH24')) AS hour_jst
FROM stamina_use_logs s
JOIN games g ON g.game_id = s.game_id;

-- 8. 時間帯別統計VIEW（全期間、期間を限定するときはVIEWにWHEREで絞り込んでから集計）
CREATE OR REPLACE VIEW v_stamina_hourly_stats AS
SELECT user_id, game_id, source, hour_jst, COUNT(*) AS use_count,
       SUM(amount) AS total_amount
FROM v_stamina_use_history
GROUP BY user_id, game_id, source, hour_jst;

-- 9. 日別統計VIEW
CREATE OR REPLACE VIEW v_stamina_daily_stats AS
SELECT user_id, game_id, source,
       TRUNC(CAST(used_at AT TIME ZONE '+09:00' AS DATE)) AS day_jst,
       COUNT(*) AS use_count, SUM(amount) AS total_amount
FROM v_stamina_use_history
GROUP BY user_id, game_id, source,
         TRUNC(CAST(used_at AT TIME ZONE '+09:00' AS DATE));

