SET DEFINE OFF
CREATE TABLE users (
  user_id       NUMBER(10) PRIMARY KEY,
  display_name  VARCHAR2(80 CHAR) NOT NULL
);

CREATE TABLE games (
  game_id       NUMBER(10) PRIMARY KEY,
  game_code     VARCHAR2(20 CHAR) NOT NULL UNIQUE,
  game_name     VARCHAR2(80 CHAR) NOT NULL,
  accent        VARCHAR2(10 CHAR) NOT NULL,
  resource_label VARCHAR2(30 CHAR) NOT NULL,
  resource_max  NUMBER(8) NOT NULL CHECK (resource_max > 0)
);

CREATE TABLE daily_tasks (
  task_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  game_id       NUMBER(10) NOT NULL REFERENCES games(game_id),
  title         VARCHAR2(80 CHAR) NOT NULL,
  target_count  NUMBER(8) DEFAULT 1 NOT NULL CHECK (target_count > 0),
  sort_order    NUMBER(5) DEFAULT 100 NOT NULL,
  is_active     NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1))
);

CREATE TABLE task_records (
  record_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id       NUMBER(10) NOT NULL REFERENCES users(user_id),
  task_id       NUMBER NOT NULL REFERENCES daily_tasks(task_id) ON DELETE CASCADE,
  record_date   DATE NOT NULL,
  progress      NUMBER(8) DEFAULT 0 NOT NULL CHECK (progress >= 0),
  note          VARCHAR2(200 CHAR),
  updated_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_daily_record UNIQUE (user_id, task_id, record_date),
  CONSTRAINT ck_record_midnight CHECK (record_date = TRUNC(record_date))
);

CREATE TABLE resource_logs (
  resource_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id       NUMBER(10) NOT NULL REFERENCES users(user_id),
  game_id       NUMBER(10) NOT NULL REFERENCES games(game_id),
  current_amount NUMBER(8) NOT NULL CHECK (current_amount >= 0),
  max_amount    NUMBER(8) NOT NULL CHECK (max_amount > 0),
  measured_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_resource_range CHECK (current_amount <= max_amount)
);

CREATE INDEX ix_records_user_day ON task_records(user_id, record_date);
CREATE INDEX ix_resource_user_game ON resource_logs(user_id, game_id, measured_at);
